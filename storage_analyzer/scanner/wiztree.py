"""Run WizTree's command-line export and parse the CSV it writes.

CSV layout (WizTree 4.33):
    line 1  "Generated by WizTree ..."                      (banner, skipped)
    line 2  File Name,Size,Allocated,Modified,Attributes,Files,Folders[,DRIVECAPACITY,FREESPACE,USEDSPACE,RESERVEDSPACE]
    rows    "C:\\Users\\",123,456,2026/10/25 21:47:34,16,65,63   folders end with '\\'; counts are recursive
The drive root row carries the four extra capacity columns.

Fast (MFT) mode needs an elevated process. We launch WizTree through an elevated PowerShell so that ONE
UAC prompt covers all drives; the rest of the app keeps normal user rights.
"""

from __future__ import annotations

import csv
import subprocess
import time
from collections.abc import Iterator
from datetime import datetime
from pathlib import Path

from .. import config
from . import Entry

CSV_FIELD_LIMIT = 1 << 20


def is_available() -> bool:
    return config.WIZTREE_EXE.exists()


def export_path(letter: str) -> Path:
    return config.EXPORT_DIR / f"wiztree_{letter}.csv"


def _ps_quote(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def run_export(letters: list[str], admin: bool = True, timeout: int = 1800) -> dict[str, Path]:
    """Export one CSV per drive. Returns {letter: csv_path}. Raises on failure."""
    if not is_available():
        raise FileNotFoundError(f"WizTree not found at {config.WIZTREE_EXE}. Run: python scripts/get_wiztree.py")
    config.ensure_dirs()
    outputs = {L: export_path(L) for L in letters}
    for p in outputs.values():
        p.unlink(missing_ok=True)

    exe = str(config.WIZTREE_EXE)
    # One PowerShell script runs every drive export sequentially. With admin=True the whole script is
    # launched elevated (-Verb RunAs), so a single UAC prompt covers all drives.
    lines = ["$ErrorActionPreference = 'Stop'"]
    for L, out in outputs.items():
        args = [f'"{L}:"', f'/export="{out}"', "/exportfolders=1", "/exportfiles=1"]
        if admin:
            args.append("/admin=1")
        lines.append(f"Start-Process -FilePath {_ps_quote(exe)} -ArgumentList {_ps_quote(' '.join(args))} -Wait")
    script_path = config.EXPORT_DIR / "run_wiztree.ps1"
    script_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    inner_args = f'-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "{script_path}"'
    if admin:
        cmd = ["powershell", "-NoProfile", "-Command",
               f"$p = Start-Process powershell -Verb RunAs -PassThru -Wait -ArgumentList {_ps_quote(inner_args)}; "
               "exit $p.ExitCode"]
    else:
        cmd = ["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", str(script_path)]

    t0 = time.time()
    proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    if proc.returncode != 0:
        raise RuntimeError(f"WizTree launch failed (exit {proc.returncode}): {proc.stderr.strip() or proc.stdout.strip()}")

    # Elevated process output is not visible to us, so verify by checking the files.
    missing = [L for L, p in outputs.items() if not p.exists() or p.stat().st_size == 0]
    if missing:
        raise RuntimeError(
            f"WizTree produced no CSV for drive(s) {', '.join(missing)}. "
            "Did you decline the admin prompt? Re-run, or use --no-admin for a slower scan.")
    # WizTree writes the file while scanning; wait until sizes stop changing.
    for p in outputs.values():
        last = -1
        while (sz := p.stat().st_size) != last:
            last = sz
            time.sleep(0.3)
    elapsed = time.time() - t0
    for L, p in outputs.items():
        print(f"  {L}: {p.stat().st_size / 1e6:.1f} MB CSV")
    print(f"WizTree export finished in {elapsed:.1f}s")
    return outputs


def _parse_mtime(s: str) -> str | None:
    # WizTree writes 'YYYY/MM/DD HH:MM:SS' in local time.
    try:
        return datetime.strptime(s, "%Y/%m/%d %H:%M:%S").isoformat(timespec="seconds")
    except ValueError:
        return None


def parse_csv(path: Path) -> tuple[dict | None, Iterator[Entry]]:
    """Returns (drive_totals, entries). drive_totals is read from the root row if present."""
    csv.field_size_limit(CSV_FIELD_LIMIT)
    f = open(path, "r", encoding="utf-8-sig", newline="")
    first = f.readline()
    if not first.startswith("Generated by WizTree"):
        f.seek(0)
    reader = csv.reader(f)
    header = next(reader)
    has_capacity = "DRIVECAPACITY" in header

    totals: dict | None = None
    root_row = next(reader, None)
    if root_row is None:
        f.close()
        return None, iter(())
    if has_capacity and len(root_row) >= 11:
        totals = {"capacity": int(root_row[7]), "free": int(root_row[8]), "used": int(root_row[9]),
                  "reserved": int(root_row[10])}

    def gen() -> Iterator[Entry]:
        try:
            for row in _chain_first(root_row, reader):
                if len(row) < 7:
                    continue
                name = row[0]
                is_dir = name.endswith("\\")
                if is_dir and len(name) > 3:
                    name = name[:-1]
                yield Entry(
                    path=name, is_dir=is_dir, size=int(row[1]), allocated=int(row[2]),
                    mtime=_parse_mtime(row[3]), attrs=int(row[4] or 0),
                    files=int(row[5] or 0) if is_dir else 0, folders=int(row[6] or 0) if is_dir else 0,
                )
        finally:
            f.close()

    return totals, gen()


def _chain_first(first, rest):
    yield first
    yield from rest
